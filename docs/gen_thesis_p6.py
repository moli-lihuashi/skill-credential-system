para('（3）前端界面开发：AI辅助生成Vue3组件模板、Element Plus表单与表格布局、Axios拦截器代码。前端路由权限控制逻辑由开发者设计。')

para('（4）论文撰写：AI辅助梳理章节框架、整理技术术语的规范表述、生成测试报告的初稿。论文的研究内容、实验数据与结论均由开发者独立完成。')

h2('D.3  代码注释与可讲解性说明')

para('按照规范要求，全部AI生成的代码均已添加中文注释，开发者能够理解每一行代码的功能与设计意图。在毕业答辩中，小组成员可以对各自负责模块的核心代码进行讲解，包括：智能合约的防篡改机制设计原理、后端哈希计算与链上交互的实现流程、前端路由权限控制的实现方式等。')

