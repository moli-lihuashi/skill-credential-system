h2('D.1  使用的AI工具')

para('本毕业设计在开发过程中积极使用了AI工具辅助编程与调试，以提高开发效率与代码质量。主要使用的AI工具包括大语言模型（Large Language Model, LLM）编程助手，用于代码生成、代码审查、技术方案讨论与文档撰写等环节。')

h2('D.2  AI辅助的具体范围')

para('（1）智能合约开发：AI辅助生成Solidity合约的初始代码框架，包括存证结构体定义、函数签名设计与事件声明。核心业务逻辑（存证唯一性校验、哈希比对核验）由开发者设计并逐行审查确认。')

