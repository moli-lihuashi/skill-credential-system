para('本系统的运行本身不依赖大模型API调用。AI工具仅在开发阶段辅助编程，不涉及系统运行时的大模型服务集成。系统的核心功能——区块链存证与哈希核验——完全基于Solidity智能合约与SHA-256密码学算法实现，不依赖任何外部AI服务。')

para('开发环境中的AI编程助手通过本地IDE插件方式调用大模型API服务，主要用于代码补全、代码解释与错误排查。这些调用不涉及系统业务数据，学生隐私信息与存证数据均未发送至外部AI服务。')

