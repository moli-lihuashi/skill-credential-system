h2('7.2  不足与展望')

para('受时间与条件限制，本系统仍存在以下不足之处，有待在未来的研究与开发中进一步完善：')

para('（1）联盟链网络方面。当前系统使用Ganache搭建本地单节点链网络进行开发与演示，尚未部署真正的多节点联盟链网络。未来工作包括搭建多机构参与的联盟链网络，实现PBFT等共识机制下的多节点存证验证。')

para('（2）IPFS集成方面。系统预留了IPFS文件存储的接口设计，但尚未实现完整的IPFS集成。后续可接入IPFS节点，实现附件文件的去中心化存储。')

para('（3）隐私保护方面。当前系统将学生ID直接写入链上，未来可引入零知识证明（Zero-Knowledge Proof）等隐私计算技术，在不泄露隐私的前提下完成成果核验。')

para('（4）性能优化方面。当存证记录数量大幅增加时，按学号遍历查询的性能会有所下降。后续可引入链下索引或事件监听机制优化查询效率。')

