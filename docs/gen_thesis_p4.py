para('（3）采用Solidity语言实现了CredentialRegistry智能合约，支持成果存证、凭证核验、操作日志上链等核心功能，通过合约的不可篡改特性保证了存证记录的可信性。')

para('（4）采用Golang语言实现了后端服务，包括用户认证、权限控制、文件哈希计算、链上交易管理、核验服务等业务逻辑，采用JWT令牌与RBAC权限控制保证系统安全。')

para('（5）采用Vue3框架实现了四套独立的前端操作界面，通过路由守卫与权限控制实现了不同角色的功能隔离，提供了友好的用户体验。')

