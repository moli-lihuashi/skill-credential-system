h2('2.1  区块链技术概述')

para('区块链（Blockchain）是一种基于密码学原理构建的分布式账本技术，其核心思想是将数据以区块（Block）的形式按时间顺序链式存储，并通过共识机制保证各节点数据的一致性与不可篡改性。区块链技术具有以下核心特性：')

para('（1）去中心化（Decentralization）。区块链网络中不存在中心化的管理机构，所有节点共同维护账本数据，任何单一节点的故障或恶意行为都不会影响整个系统的正常运行。')

para('（2）不可篡改（Immutability）。每个区块包含前一区块的哈希值，形成链式结构。修改任何一个历史区块的数据都会导致后续所有区块的哈希值发生变化，在计算上不可行，从而保证了数据的不可篡改性。')

para('（3）可追溯（Traceability）。区块链上的每一笔交易都有完整的记录，可以通过链式结构追溯到数据的源头，形成完整的审计链条。')

para('（4）公开透明（Transparency）。区块链网络中的所有节点都可以查看链上的数据，保证了信息的公开透明。')

para('（5）共识机制（Consensus Mechanism）。区块链网络通过共识机制（如工作量证明PoW、权益证明PoS、实用拜占庭容错PBFT等）保证各节点对账本数据达成一致。')

para('按照开放程度的不同，区块链可以分为公有链（Public Blockchain）、私有链（Private Blockchain）和联盟链（Consortium Blockchain）三种类型。公有链对所有人开放，任何人都可以参与共识与数据维护，典型代表有比特币、以太坊；私有链由单一组织控制，仅对内部成员开放；联盟链则由若干授权机构共同维护，参与节点需要经过身份认证，兼顾了公有链的可信性与私有链的高效性。')

h2('2.2  联盟链技术')

para('联盟链（Consortium Blockchain）是区块链技术面向行业应用的重要形态。与公有链相比，联盟链的参与节点是经过授权的机构或组织，而非任意个体。联盟链通常采用高效的共识机制（如PBFT、Raft等），交易确认速度快、吞吐量高，同时通过权限管理机制保证了数据的隐私性。')

para('联盟链的这些特点使其特别适合教育存证场景：（1）参与节点（学校、实训企业）是可信的授权机构，保证了存证信息的权威性；（2）高效的共识机制满足了教育业务对响应速度的要求；（3）权限管理机制保证了学生隐私数据不被未授权方访问；（4）不可篡改特性保证了存证记录的可信性。')

para('本系统采用Solidity语言编写智能合约，底层可运行在以太坊兼容的联盟链网络上。在开发与演示阶段，系统使用Ganache工具搭建本地区块链网络进行测试；在生产部署阶段，可扩展接入企业级联盟链平台。')

h2('2.3  Solidity智能合约')

