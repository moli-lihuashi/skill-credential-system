para('Solidity语言具有以下特点：（1）语法类似于JavaScript与C++，学习曲线平缓；（2）支持静态类型、继承、库、复杂的用户自定义类型等高级特性；（3）编译后生成字节码与应用程序二进制接口（ABI），供外部调用；（4）运行在以太坊虚拟机上，具有图灵完备的计算能力。')

