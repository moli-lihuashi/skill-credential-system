# ==================== 第4章 系统设计 ====================
h1('第4章  系统设计')

para('本章在需求分析的基础上进行系统的总体架构设计、智能合约设计、数据库设计、接口设计与前端设计，为系统实现提供详细的设计方案。')

h2('4.1  总体架构设计')

para('系统采用前后端分离的B/S架构，整体划分为四个层次：展示层、业务层、联盟链层与数据层。各层职责清晰，层间通过标准化接口进行交互。')

h3('4.1.1  展示层')

para('展示层采用Vue3框架开发，针对四类角色分别设计独立的操作界面：学生端（个人中心、我的存证）、院校管理端（工作台、成果录入、存证管理、操作日志）、实训企业端（工作台、实训成果录入）、招聘企业核验端（凭证核验、核验历史）。展示层通过HTTP协议与业务层进行RESTful API交互，使用JWT令牌进行身份认证。')

h3('4.1.2  业务层')

para('业务层采用Golang语言开发，基于Gin框架提供RESTful API服务。业务层包含以下核心服务模块：')

para('（1）账号权限服务：负责用户注册、登录、JWT令牌签发与验证、角色权限控制。注册时自动生成区块链公私钥对与链账户地址。')
para('（2）成果管理服务：负责技能成果的录入、查询、附件上传与文件哈希计算。')
para('（3）存证服务：负责调用智能合约进行成果上链，管理存证凭证记录。')
para('（4）核验服务：负责处理外部核验请求，比对文件哈希，输出核验结果。')
para('（5）日志服务：负责记录全部操作日志，计算日志哈希并批量上链。')
para('（6）文件服务：负责附件文件的存储管理，支持本地存储与IPFS扩展。')

h3('4.1.3  联盟链层')

para('联盟链层由Solidity智能合约与区块链网络组成。核心合约CredentialRegistry负责成果存证、凭证核验、操作日志上链等业务逻辑。合约部署在联盟链网络上，由授权节点（学校、实训企业）共同维护。开发与演示阶段使用Ganache搭建本地链网络，生产环境可扩展接入企业级联盟链平台。')

h3('4.1.4  数据层')

para('数据层由MySQL数据库与文件存储服务组成。MySQL存储用户信息、成果元数据、存证凭证、核验日志、系统日志等结构化数据。附件文件存储在本地文件服务器或IPFS网络中。数据层遵循"链上存哈希、链下存原文"的隐私保护原则。')

h2('4.2  智能合约设计')

h3('4.2.1  合约总体设计')

para('系统核心智能合约为CredentialRegistry（存证注册合约），采用Solidity 0.8.19版本编写。合约主要包含以下数据结构与功能接口：')

para('存证数据结构Credential：包含唯一存证编号（credentialNo）、学生ID（studentId）、成果类型（achievementType）、成果名称（title）、文件哈希（fileHash）、上链时间戳（timestamp）、上链节点地址（issuer）、上链单位名称（issuerName）与存在标记（exists）。')

para('合约功能接口包括：')
para('（1）storeCredential：成果上链存证。仅授权节点可调用。参数包括存证编号、学生ID、成果类型、成果名称、文件哈希、单位名称。合约校验存证编号唯一性后写入存储，并触发CredentialStored事件。')
para('（2）verifyCredential：凭证核验。接收存证编号与文件哈希，与链上存储的哈希进行比对，返回核验结果与存证元数据。')
para('（3）getCredential：只读查询。根据存证编号查询链上存证信息。')
para('（4）getCredentialNosByStudent：按学号查询存证编号列表。')
para('（5）logOperation：操作日志上链。将操作日志的SHA-256哈希写入链上，保护日志隐私。')
para('（6）addAuthorizedNode / removeAuthorizedNode：授权节点管理，仅合约所有者可调用。')

h3('4.2.2  不可篡改机制设计')

para('合约通过以下机制保证数据的不可篡改性：（1）存证编号全局唯一，storeCredential函数使用require(!credentials[credentialNo].exists)语句拒绝重复写入；（2）合约不提供update与delete功能，存证数据一旦写入无法修改或删除；（3）credentials映射使用私有（private）访问修饰符，只能通过合约函数访问，外部无法直接修改状态变量；（4）全部操作触发事件（Event）记录，形成链上审计日志。')

h3('4.2.3  核验机制设计')

para('核验机制的核心是哈希比对。当招聘企业提供存证编号与待核验文件时，系统对文件计算SHA-256哈希，调用合约的verifyCredential函数，将传入哈希与链上存储的哈希进行比较。若两个哈希值完全一致，说明文件内容自存证以来未被篡改，输出"核验通过（数据未篡改）"；若不一致，说明文件内容可能已被篡改，输出"核验不通过（信息存在篡改风险）"。')

para('SHA-256算法的雪崩效应保证了即使文件内容仅发生一个比特位的改变，其哈希值也会发生显著变化，使得篡改行为在计算上可被检测。')

h2('4.3  数据库设计')

para('系统采用MySQL关系型数据库，共设计五张核心数据表。')

h3('4.3.1  用户表（users）')

para('用户表存储系统全部注册用户的信息，主要字段包括：主键id、登录名username（唯一索引）、密码password（bcrypt哈希）、真实姓名real_name、学号student_no、角色role（枚举：student/school_admin/company/employer）、单位名称org_name、链账户地址eth_address、链账户私钥eth_private_key（演示环境存储，生产应加密托管）、状态status、注册时间created_at。')

h3('4.3.2  成果表（achievements）')

para('成果表存储录入的技能成果信息，主要字段包括：主键id、学生ID student_id、成果名称title、成果类型ach_type（枚举：certificate/competition/internship/project）、成果描述description、颁发单位issuer、文件哈希file_hash（SHA-256）、文件路径file_path、状态status（draft/submitted/onchain）、录入人created_by、录入时间created_at。')

h3('4.3.3  存证凭证表（credentials）')

para('存证凭证表是系统的核心表，存储区块链存证凭证的链下映射。主要字段包括：主键id、唯一存证编号credential_no（唯一索引）、成果ID achievement_id、学生ID、姓名快照、学号快照、成果类型快照、成果名称快照、链上交易哈希chain_tx_hash、区块高度chain_block_no、文件哈希file_hash、上链节点地址、上链时间onchain_time、核验次数verify_count、状态status。')

para('本表遵循严格的只增原则：业务数据仅允许INSERT操作，禁止UPDATE与DELETE操作（仅verify_count可递增），对应任务书中"链上历史记录不可删除修改"的要求。')

h3('4.3.4  核验记录表（verify_logs）')

para('核验记录表存储每次外部核验的详细记录，主要字段包括：主键id、被核验凭证编号credential_no、核验企业ID employer_id、核验企业名称、传入文件哈希input_hash、链上核验结果chain_result（pass/fail）、核验时间created_at。')

h3('4.3.5  系统日志表（sys_logs）')

para('系统日志表记录全部操作日志，主要字段包括：主键id、操作人ID user_id、操作人用户名、操作类型action、操作详情detail、日志哈希log_hash（本条日志的SHA-256）、批次哈希batch_hash（批量上链后回填）、是否上链onchain、操作时间created_at。')

h2('4.4  接口设计')

para('系统后端提供RESTful API接口，主要接口设计如下：')

para('（1）POST /api/auth/register：用户注册。请求参数：用户名、密码、姓名、角色、学号（学生必填）、单位名称。响应：用户ID、链账户地址。')
